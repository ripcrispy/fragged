// Regenerate src/generated/modules.ts from ./modules/*/index.ts and the npm packages listed in fragged.config.json.
// Runs automatically before dev/build/test; commit the result. `--check` exits 1 if the file is out of date (CI).
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'src/generated/modules.ts');
const config = fs.existsSync(path.join(root, 'fragged.config.json')) ? JSON.parse(fs.readFileSync(path.join(root, 'fragged.config.json'), 'utf8')) : {};
const local = fs.existsSync(path.join(root, 'modules'))
  ? fs.readdirSync(path.join(root, 'modules')).sort().map((d) => ({ d, entry: ['index.ts', 'index.tsx'].find((f) => fs.existsSync(path.join(root, 'modules', d, f))) })).filter((x) => x.entry)
  : [];
const packages = (config.modules ?? []).filter((p) => typeof p === 'string');
const lines = [
  '// GENERATED by scripts/sync-modules.mjs — do not edit. Lists every installed module.',
  "import path from 'node:path';",
  "import { createRequire } from 'node:module';",
  "import type { InstalledModule } from '../modules/runtime.ts';",
];
local.forEach(({ d, entry }, i) => lines.push(`import local${i} from '../../modules/${d}/${entry}';`));
packages.forEach((p, i) => lines.push(`import pkg${i} from ${JSON.stringify(p)};`));
lines.push(packages.length
  ? "import fs from 'node:fs';\nconst req = createRequire(import.meta.url);\n/** Folder of an installed package (works whether or not its \"exports\" lists package.json). */\nconst pkgDir = (name: string) => { let d = path.dirname(req.resolve(name)); while (!fs.existsSync(path.join(d, 'package.json')) || JSON.parse(fs.readFileSync(path.join(d, 'package.json'), 'utf8')).name !== name) { const up = path.dirname(d); if (up === d) throw new Error(`cannot locate package ${name}`); d = up; } return d; };"
  : 'void createRequire;');
lines.push('', 'export const installedModules: InstalledModule[] = [');
local.forEach(({ d }, i) => lines.push(`  { def: local${i}, dir: path.resolve('modules', ${JSON.stringify(d)}), source: 'local' },`));
packages.forEach((p, i) => lines.push(`  { def: pkg${i}, dir: pkgDir(${JSON.stringify(p)}), source: 'package' },`));
lines.push('];', '');
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== text) { console.error('src/generated/modules.ts is out of date — run `npm run modules:sync`'); process.exit(1); }
  process.exit(0);
}
// npm-package modules import the SDK as `fragged-forums/sdk` (package.json "exports"). Link this app into
// node_modules so Node resolves that specifier to the one copy of src/sdk (the production build aliases it instead).
if (packages.length && !process.argv.includes('--check')) {
  const link = path.join(root, 'node_modules', 'fragged-forums');
  let ok = false;
  try { ok = fs.realpathSync(link) === root; } catch { /* missing */ }
  if (!ok) { fs.rmSync(link, { force: true, recursive: false }); fs.symlinkSync('..', link, 'dir'); }
}
fs.mkdirSync(path.dirname(out), { recursive: true });
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) fs.writeFileSync(out, text);
console.log(`modules: ${local.length} local, ${packages.length} package(s)`);
